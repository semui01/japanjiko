"""Reduce the japanjiko datasets to the numbers the film shows, and write video/data.js.

usage: python3 data/prepare.py <path to the semui01/japanjiko checkout> [out=data.js]

Every number on screen comes from this script's output. Source: github.com/semui01/japanjiko
(data/*.csv), which compiles MHLW Vital Statistics of Japan (final data) via e-Stat and the MHLW
FY2009 special report on accidental deaths.
"""
import csv, json, sys, os

repo = sys.argv[1]
out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(os.path.dirname(__file__), '..', 'data.js')
D = os.path.join(repo, 'data')
rd = lambda f: list(csv.DictReader(open(os.path.join(D, f), encoding='utf-8')))
num = lambda s: None if s in ('', None) else (float(s) if '.' in s else int(s))

# Figure 1: accidental deaths per year, 1899–2025 (no records 1944–1946)
long_run = [[int(r['year']), int(r['accidental_deaths'])] for r in rd('long_run.csv')]

# Figure 2: deaths by main type, 1995–2025
types = ['traffic', 'falls', 'drowning', 'choking', 'fire', 'poisoning']
bt = rd('by_type.csv')
by_type = {'years': [int(r['year']) for r in bt], **{k: [int(r[k]) for r in bt] for k in types + ['total']}}

# Figure 3: drowning rate per 100,000 by age, 2008 vs 2024 (ages 65–89)
ages = ['65–69', '70–74', '75–79', '80–84', '85–89']
ar = rd('age_rates.csv')
drown = {a: {y: float(next(r for r in ar if r['year'] == y and r['age'] == a)['drowning']) for y in ('2008', '2024')} for a in ages}
drown_rates = [[a, drown[a]['2008'], drown[a]['2024']] for a in ages]
assert all(d24 > d08 for _, d08, d24 in drown_rates), 'drowning rate did not rise at every age 65–89'

# Figure 8: 2025 deaths by age group and type (unknown age left out, as in the app)
stack = ['falls', 'drowning', 'choking', 'traffic', 'fire', 'poisoning', 'other']
ag = rd('age_groups_2025.csv')
age25 = [[r['age_group'], int(r['total'])] + [int(r[k]) for k in stack] for r in ag if r['age_group'] != 'unknown']
for row in age25:
    assert sum(row[2:]) == row[1], row
tot25 = next(v for y, v in long_run if y == 2025)
assert tot25 == by_type['total'][-1] == sum(int(r['total']) for r in ag)
old = sum(r[1] for r in age25 if r[0] in ('65–79', '80 and over'))
share65 = round(100 * old / tot25, 1)

y = by_type['years']
i08, i25 = y.index(2008), y.index(2025)
pct = lambda k: round(100 * (by_type[k][i25] - by_type[k][i08]) / by_type[k][i08], 1)

DATA = {
    'longRun': long_run,
    'byType': by_type,
    'drownRates': drown_rates,
    'age25': {'stack': stack, 'rows': age25},
    'facts': {
        'tot2025': tot25, 'tot2008': by_type['total'][i08], 'vs2008': pct('total'),
        'falls2025': by_type['falls'][i25], 'drown2025': by_type['drowning'][i25], 'traffic2025': by_type['traffic'][i25],
        'fallsPct': pct('falls'), 'drownPct': pct('drowning'), 'trafficPct': pct('traffic'),
        'share65': share65, 'old65': old,
        'quakes': [1923, 1995, 2011],
    },
}
open(out, 'w', encoding='utf-8').write('// generated by data/prepare.py from github.com/semui01/japanjiko data/*.csv\nwindow.DATA = ' + json.dumps(DATA, ensure_ascii=False) + ';\n')
print(json.dumps(DATA['facts'], ensure_ascii=False), DATA['drownRates'])
