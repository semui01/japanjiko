def fetch(url: str, dest: pathlib.Path) -> None:
    dest.parent.mkdir(parents=True, exist_ok=True)
    with urllib.request.urlopen(url, timeout=60) as r:
        dest.write_bytes(r.read())
    print(f"saved {dest.relative_to(ROOT)}")


def main() -> None:
    seen = set()
    for name, sid, kind, _title in ESTAT_TABLES + EXPLORER_TABLES:
        if name in seen:
            continue
        seen.add(name)
        fetch(ESTAT.format(sid=sid, kind=kind), RAW / "estat" / f"{name}.csv")
        time.sleep(0.3)
    fetch(MHLW_XLS, RAW / "mhlw_furyo10" / "toukeihyo.xls")


if __name__ == "__main__":
    main()
